"""Exports the contract: `python -m vitae.schema <contract dir>` writes the JSON Schema and the example streams.

json-schema-to-typescript turns the schema into contract/vitae-contract.ts (see `npm run contract`)."""

import json
import sys
from pathlib import Path
from typing import Annotated, Any, Final

from pydantic import Field, TypeAdapter
from pydantic.json_schema import GenerateJsonSchema, JsonSchemaMode

from vitae.contract import (
    OUTCOMES,
    ChatRequest,
    ErrorResponse,
    FinalCode,
    Finish,
    RefusalReason,
    Rejection,
    RetryableCode,
    StreamErrorCode,
    StreamEvent,
    TerminalEvent,
)
from vitae.fixtures import FIXTURES, Raw, RejectionFixture, StreamFixture
from vitae.wire import encode_event, encode_rejection

SCHEMA_FILE: Final = "vitae-contract.schema.json"
STREAMS_DIR: Final = "streams"
REF_TEMPLATE: Final = "#/$defs/{model}"


class _ContractSchema(GenerateJsonSchema):
    # Property titles make json2ts declare a type alias per property (`export type Message = string`).
    def field_title_should_be_set(self, schema: Any) -> bool:
        return False


# Shapes pydantic inlines that TS consumers should see by name. Wherever one of these schemas
# appears inline, it is replaced by a $ref to its own definition.
_NAMED: Final[dict[str, tuple[Any, JsonSchemaMode]]] = {
    "Rejection": (Annotated[Rejection, Field(discriminator="code")], "serialization"),
    "StreamEvent": (Annotated[StreamEvent, Field(discriminator="type")], "serialization"),
    "TerminalEvent": (Annotated[TerminalEvent, Field(discriminator="type")], "serialization"),
    "RetryableCode": (RetryableCode, "serialization"),
    "FinalCode": (FinalCode, "serialization"),
    "RefusalReason": (RefusalReason, "serialization"),
    "StreamErrorCode": (StreamErrorCode, "serialization"),
    "Finish": (Finish, "serialization"),
}


def contract_schema() -> dict[str, Any]:
    """One document. Root object VitaeContract with request (validation mode), errorResponse, event
    and outcome (serialization mode), so json2ts emits every type, plus $defs."""
    inputs = [
        ("request", "validation", TypeAdapter(ChatRequest)),
        ("errorResponse", "serialization", TypeAdapter(ErrorResponse)),
        *((name, mode, TypeAdapter(shape)) for name, (shape, mode) in _NAMED.items()),
    ]
    by_key, top = TypeAdapter.json_schemas(inputs, ref_template=REF_TEMPLATE, schema_generator=_ContractSchema)
    defs: dict[str, Any] = top["$defs"]
    named = {name: by_key[(name, mode)] for name, (_, mode) in _NAMED.items()}
    defs |= {name: _ref_named(schema, named) for name, schema in defs.items()}
    defs |= {name: {"title": name, **schema} for name, schema in named.items()}
    defs["Outcome"] = {
        "title": "Outcome",
        "description": "What the UI and the eval graders switch on. A pure function of the rejection or terminal event.",
        "type": "string",
        "enum": list(OUTCOMES),
    }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "VitaeContract",
        "description": "The HTTP and SSE contract for POST /v1/chat. Generated by `python -m vitae.schema`.",
        "type": "object",
        "properties": {
            "request": by_key[("request", "validation")],
            "errorResponse": by_key[("errorResponse", "serialization")],
            "event": {"$ref": REF_TEMPLATE.format(model="StreamEvent")},
            "outcome": {"$ref": REF_TEMPLATE.format(model="Outcome")},
        },
        "required": ["request", "errorResponse", "event", "outcome"],
        "additionalProperties": False,
        "$defs": dict(sorted(defs.items())),
    }


def _ref_named(node: Any, named: dict[str, Any]) -> Any:
    for name, schema in named.items():
        if node == schema:
            return {"$ref": REF_TEMPLATE.format(model=name)}
    if isinstance(node, dict):
        return {key: _ref_named(value, named) for key, value in node.items()}
    if isinstance(node, list):
        return [_ref_named(value, named) for value in node]
    return node


def export(contract_dir: Path) -> None:
    """Rewrites the schema and every example stream. Files of removed fixtures are deleted."""
    streams = contract_dir / STREAMS_DIR
    streams.mkdir(parents=True, exist_ok=True)
    for stale in streams.iterdir():
        stale.unlink()
    _write(contract_dir / SCHEMA_FILE, _json(contract_schema()))

    expected: dict[str, Any] = {}
    for fixture in FIXTURES:
        match fixture:
            case StreamFixture():
                file, status = f"{fixture.name}.sse", 200
                body = b"".join(f.frame if isinstance(f, Raw) else encode_event(f) for f in fixture.frames)
            case RejectionFixture():
                status, body, _ = encode_rejection(fixture.rejection)
                file = f"{fixture.name}.json"
        (streams / file).write_bytes(body)
        expected[fixture.name] = {
            "file": file,
            "status": status,
            "outcome": fixture.expected.outcome,
            "text": fixture.expected.text,
            "streamedThenFailed": fixture.expected.streamed_then_failed,
            "sessionId": fixture.expected.session_id,
            "sources": [source.model_dump(mode="json") for source in fixture.expected.sources],
        }
    _write(streams / "expected.json", _json(expected))


def _json(value: Any) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def _write(path: Path, text: str) -> None:
    path.write_bytes(text.encode())


if __name__ == "__main__":
    export(Path(sys.argv[1] if len(sys.argv) > 1 else "contract"))
